#!/usr/bin/env python3
"""Documentation consistency check (verify_docs.py)

Why this exists: the project repeatedly drifted between "README says 88%" and
"the gate measured 86%". Documents are deliverables, so version numbers, tool
counts, assertion counts and file paths must be *checkable*, never hand-typed.

Single source of truth for every published number is `docs/metrics.json`,
generated by `scripts/metrics.py`. This script recomputes the static counts
from the source tree and fails if any document quotes a different value.

Checks:
  D1   version single source: __init__.py == pyproject.toml == README
  D2   MCP tool count: @server.tool decorators == world_schema registry == README
  D3   every screenshot / demo save referenced by a README exists and is non-empty
  D4   every scripts/*.py mentioned in a doc exists
  D5   ARCHITECTURE carries a readable document version
  D6   CHANGELOG contains the current version entry
  D7   the Pages site references only existing screenshots
  D8   no TODO/FIXME placeholders in production code
  D9   demo save index covers every .save.json
  D10  every setting bundle is registered in settings/README.md
  D11  published rule-function count == rules/ public top-level functions
  D12  published self-check count == scripts/verify_*.py
  D12b the behavior regressions are registered and wired into all three gates
  D13  English README and the site agree on the tool count
  D14  every Markdown file's script references resolve
  D15  site relative links stay inside the site root
  D16  the README quick-start trade example is actually executable
  D17  archive-pending handling is documented with the recovery guide linked
  D18  the site does not hardcode mutation or gate results
  D19  every published count matches docs/metrics.json
  D20  both READMEs exist, link to each other, and the English one is English

Usage:  python scripts/verify_docs.py
Exit:   0 = consistent, 1 = drift
"""

import ast
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = []

# README.md is the English primary; README.zh-CN.md is the Chinese edition.
PRIMARY = 'README.md'
SECONDARY = 'README.zh-CN.md'


def check(name, ok, note=''):
    RESULTS.append(bool(ok))
    print('%s  %-56s %s' % ('PASS' if ok else 'FAIL', name, str(note)[:90]))


def read(rel):
    with open(os.path.join(ROOT, rel), encoding='utf-8') as fh:
        return fh.read()


def load_metrics():
    path = os.path.join(ROOT, 'docs', 'metrics.json')
    if not os.path.isfile(path):
        return {}
    with open(path, encoding='utf-8') as fh:
        return json.load(fh)


def version():
    match = re.search(r'__version__\s*=\s*"([^"]+)"', read('__init__.py'))
    return match.group(1) if match else None


def count_tools():
    tree = ast.parse(read('mcp_server.py'))
    names = set()
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for deco in node.decorator_list:
            func = deco.func if isinstance(deco, ast.Call) else deco
            if (isinstance(func, ast.Attribute) and func.attr == 'tool'
                    and isinstance(func.value, ast.Name) and func.value.id == 'server'):
                names.add(node.name)
    return names


def count_rule_functions():
    total = 0
    for name in sorted(os.listdir(os.path.join(ROOT, 'rules'))):
        if not name.endswith('.py'):
            continue
        tree = ast.parse(read(os.path.join('rules', name)))
        total += sum(1 for node in tree.body
                     if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
                     and not node.name.startswith('_'))
    return total


def main():
    metrics = load_metrics()
    ver = version()
    primary = read(PRIMARY)
    secondary = read(SECONDARY)

    # ── D1 version single source ────────────────────────────────────────────
    check('D1a __init__.py declares a version', bool(ver), ver)
    match = re.search(r'^version\s*=\s*"([^"]+)"', read('pyproject.toml'), re.M)
    check('D1b pyproject.toml matches __init__.py',
          bool(match) and match.group(1) == ver,
          '%s vs %s' % (match.group(1) if match else None, ver))
    check('D1c README states the current version', ver in primary, ver)

    # ── D2 tool count ───────────────────────────────────────────────────────
    decorated = count_tools()
    tool_count = len(decorated)
    check('D2a all tool functions parse statically', tool_count > 25, '%d tools' % tool_count)

    registered = None
    tree = ast.parse(read('mcp_server.py'))
    for node in ast.walk(tree):
        if isinstance(node, ast.Dict):
            keys = [k.value for k in node.keys
                    if isinstance(k, ast.Constant) and isinstance(k.value, str)]
            if 'world_init' in keys and 'tick' in keys and len(keys) > 20:
                registered = set(keys)
                break
    check('D2b world_schema registers exactly the real tools',
          registered is not None and registered == decorated,
          'missing=%s' % (sorted(decorated - (registered or set()))[:4],))

    claimed = (re.findall(r'`(\d+)\s*MCP\s*tools`', primary)
               + re.findall(r'##\s*The\s*(\d+)\s*tools', primary)
               + re.findall(r'MCP server,\s*(\d+)\s*tools', primary))
    check('D2c README tool count matches source',
          bool(claimed) and all(int(c) == tool_count for c in claimed),
          'readme=%s actual=%d' % (claimed[:4], tool_count))

    # ── D3 referenced assets ────────────────────────────────────────────────
    missing = []
    for doc in (PRIMARY, SECONDARY):
        text = read(doc)
        refs = re.findall(r'\]\((docs/[^)\s]+)\)', text) + re.findall(r'src="(docs/[^"]+)"', text)
        for ref in refs:
            path = os.path.join(ROOT, ref)
            if not os.path.exists(path) or os.path.getsize(path) == 0:
                missing.append('%s → %s' % (doc, ref))
    check('D3 README asset references resolve and are non-empty', not missing, str(missing[:3]))

    # ── D4 script references ────────────────────────────────────────────────
    ghost = []
    for doc in (PRIMARY, SECONDARY, 'CONTRIBUTING.md', 'AGENTS.md', 'ARCHITECTURE.md'):
        for ref in set(re.findall(r'scripts/([A-Za-z0-9_]+\.py)', read(doc))):
            if not os.path.exists(os.path.join(ROOT, 'scripts', ref)):
                ghost.append('%s → scripts/%s' % (doc, ref))
    check('D4 referenced scripts exist', not ghost, str(ghost[:3]))

    # ── D5 architecture version ─────────────────────────────────────────────
    arch = read('ARCHITECTURE.md')
    match = re.search(r'文档版本：v(\d+)\.(\d+)', arch)
    check('D5 ARCHITECTURE declares a document version', bool(match),
          match.group(0) if match else '—')

    # ── D6 changelog ────────────────────────────────────────────────────────
    changelog = read('CHANGELOG.md')
    check('D6 CHANGELOG has an entry for the current version', ('v' + ver) in changelog, ver)

    # ── D7 site assets ──────────────────────────────────────────────────────
    pages = read('docs/index.html')
    page_missing = [ref for ref in re.findall(r'(?:src|href)="(screenshots/[^"]+)"', pages)
                    if not os.path.exists(os.path.join(ROOT, 'docs', ref))]
    check('D7 site screenshots and video exist', not page_missing, str(page_missing[:3]))

    # ── D7b bilingual assertion tables agree ────────────────────────────────
    primary_claims = re.findall(r'`verify_[a-z_0-9]+\.py` \| (\d+)', primary)
    secondary_claims = re.findall(r'`verify_[a-z_0-9]+\.py` \| (\d+)', secondary)
    check('D7b both READMEs publish identical assertion counts',
          primary_claims == secondary_claims,
          'en=%s zh=%s' % (primary_claims[:4], secondary_claims[:4]))

    # ── D7c Pages workflow self-enables ─────────────────────────────────────
    pages_wf = read('.github/workflows/pages.yml')
    check('D7c Pages workflow self-enables the site on first run',
          'enablement: true' in pages_wf and 'pages: write' in pages_wf)

    # ── D8 no debt markers ──────────────────────────────────────────────────
    todo = [name for name in ('engine.py', 'mcp_server.py', 'panel.py', 'state_schema.py',
                              'viz_series.py', '__init__.py')
            if re.search(r'\b(TODO|FIXME|XXX)\b', read(name))]
    check('D8 production code has no TODO/FIXME placeholders', not todo, str(todo))

    # ── D9 demo index ───────────────────────────────────────────────────────
    demo_readme = read('docs/demo/README.md')
    demo_files = sorted(f for f in os.listdir(os.path.join(ROOT, 'docs', 'demo'))
                        if f.endswith('.save.json'))
    listed = [f for f in demo_files if f in demo_readme]
    check('D9 demo index covers every .save.json', len(listed) == len(demo_files),
          '%d/%d' % (len(listed), len(demo_files)))

    # ── D10 bundles registered ──────────────────────────────────────────────
    settings_readme = read('settings/README.md')
    bundles = sorted(f[:-len('.setting.json')]
                     for f in os.listdir(os.path.join(ROOT, 'settings'))
                     if f.endswith('.setting.json'))
    check('D10 every setting bundle is registered in settings/README.md',
          all(b in settings_readme for b in bundles), str(bundles))

    # ── D11 rule function count ─────────────────────────────────────────────
    rule_funcs = count_rule_functions()
    claimed_funcs = []
    for doc in (PRIMARY, SECONDARY, 'docs/index.html'):
        text = read(doc)
        claimed_funcs += [int(x) for x in re.findall(r'(\d+)\s*个规则函数', text)]
        claimed_funcs += [int(x) for x in re.findall(r'(\d+)\s*rule functions', text)]
    check('D11 published rule-function count matches source',
          bool(claimed_funcs) and all(c == rule_funcs for c in claimed_funcs),
          'docs=%s actual=%d' % (sorted(set(claimed_funcs)), rule_funcs))

    # ── D12 self-check count ────────────────────────────────────────────────
    verify_scripts = [f for f in os.listdir(os.path.join(ROOT, 'scripts'))
                      if f.startswith('verify_') and f.endswith('.py')]
    claimed_checks = []
    for doc in (PRIMARY, SECONDARY, 'docs/index.html'):
        text = read(doc)
        claimed_checks += [int(x) for x in re.findall(r'(\d+)\s*个可执行自检', text)]
        claimed_checks += [int(x) for x in re.findall(r'(\d+)\s*executable self-checks', text)]
        claimed_checks += [int(x) for x in re.findall(r'(\d+)\s*verify_\*\s*(?:suites|自检)', text)]
        claimed_checks += [int(x) for x in re.findall(r'(\d+)\s*self-check', text)]
    check('D12 published self-check count matches scripts/',
          bool(claimed_checks) and all(c == len(verify_scripts) for c in claimed_checks),
          'docs=%s actual=%d' % (sorted(set(claimed_checks)), len(verify_scripts)))

    runner = ast.parse(read('scripts/run_behavior_regressions.py'))
    modules = set()
    for node in runner.body:
        if (isinstance(node, ast.Assign)
                and any(isinstance(t, ast.Name) and t.id == 'MODULES' for t in node.targets)
                and isinstance(node.value, (ast.Tuple, ast.List))):
            modules = {item.value for item in node.value.elts
                       if isinstance(item, ast.Constant) and isinstance(item.value, str)}
    required = {'tests_checks_regression', 'tests_turn_regression', 'tests_mutation_regression',
                'tests_mcp_regression', 'tests_archive_crash_regression'}
    missing = sorted(name for name in required
                     if name not in modules or not os.path.isfile(os.path.join(ROOT, name + '.py')))
    runner_path = 'scripts/run_behavior_regressions.py'
    gates = ('scripts/pre_push_gate.sh', '.github/workflows/ci.yml', '.workflow/ci.yml')
    missing_gates = [gate for gate in gates if not re.search(
        r'^[^\n#]*\bpython\s+' + re.escape(runner_path) + r'\b', read(gate), re.M)
        and not re.search(r'^step\s+[^\n]*"\$PY"\s+' + re.escape(runner_path) + r'\b',
                          read(gate), re.M)]
    check('D12b behavior regressions are registered and wired into all gates',
          not missing and not missing_gates,
          'missing=%s gates=%s' % (missing, missing_gates))

    # ── D13 English README and site agree on tool count ─────────────────────
    # The site localises the badge label, so match the number in its own <b> and
    # require the label to be one of the two accepted localisations. Matching the
    # English label alone would silently pass when the label is translated.
    en_claimed = [int(x) for x in re.findall(r'(\d+)\s*MCP tools', primary)]
    site_badges = re.findall(r'<b>(\d+)</b>\s*<span data-lang="en">MCP tools</span>', pages)
    site_tools = [int(x) for x in site_badges]
    site_rule_funcs = [int(x) for x in re.findall(
        r'<b>(\d+)</b>\s*<span data-lang="en">rule functions</span>', pages)]
    check('D13 English README and site agree on the tool count',
          bool(en_claimed) and bool(site_tools)
          and all(c == tool_count for c in en_claimed + site_tools)
          and all(c == rule_funcs for c in site_rule_funcs),
          'readme=%s site=%s rule_funcs=%s actual=%d'
          % (en_claimed, site_tools, site_rule_funcs, tool_count))

    # ── D14 every Markdown script reference resolves ────────────────────────
    ghost = []
    for base, _dirs, files in os.walk(ROOT):
        parts = base.split(os.sep)
        if '.git' in parts or '.aqg' in parts or '.tmp' in parts:
            continue
        for fname in files:
            if not fname.endswith('.md'):
                continue
            path = os.path.join(base, fname)
            rel = os.path.relpath(path, ROOT).replace(os.sep, '/')
            # Dated audit reports are snapshots; they may cite scripts that no longer exist.
            if rel.startswith('docs/AUDIT_') or rel.startswith('docs/PROJECT_AUDIT_'):
                continue
            with open(path, encoding='utf-8') as fh:
                text = fh.read()
            for ref in set(re.findall(r'scripts/([A-Za-z0-9_]+\.py)', text)):
                if not os.path.exists(os.path.join(ROOT, 'scripts', ref)):
                    ghost.append('%s → scripts/%s' % (rel, ref))
    check('D14 all Markdown script references resolve', not ghost, str(ghost[:3]))

    # ── D15 site links stay inside the site root ────────────────────────────
    bad_links = []
    for ref in re.findall(r'href="([^"#:]+)"', pages):
        if ref.startswith(('http', 'mailto')):
            continue
        if ref.startswith('../'):
            bad_links.append(ref)
            continue
        if not os.path.exists(os.path.join(ROOT, 'docs', ref)):
            bad_links.append(ref)
    check('D15 site relative links resolve inside the site root', not bad_links,
          str(bad_links[:3]))

    # ── D16 quick-start example is executable ───────────────────────────────
    match = re.search(
        r'trade\(location="([^"]+)", item="([^"]+)", direction="(buy|sell)", quantity=(\d+)\)',
        primary)
    bundle = None
    if match:
        for fname in os.listdir(os.path.join(ROOT, 'settings')):
            if fname.endswith('.setting.json'):
                data = json.loads(read(os.path.join('settings', fname)))
                if (data.get('world') or {}).get('name') == '玄枢界':
                    bundle = data
                    break
    ok_quick = False
    note = 'example not found'
    if match and bundle:
        loc, item, direction, qty = match.group(1), match.group(2), match.group(3), int(match.group(4))
        market = {entry.get('location'): entry for entry in bundle.get('market') or []}
        items = {entry.get('key'): entry for entry in (market.get(loc) or {}).get('items') or []}
        entry = items.get(item)
        gold = int((bundle.get('player') or {}).get('gold', 0) or 0)
        if entry and direction == 'buy':
            ok_quick = gold >= int(entry.get('price', 0)) * qty
            note = 'gold=%d price=%s qty=%d' % (gold, entry.get('price'), qty)
        elif entry and direction == 'sell':
            held = int(((bundle.get('player') or {}).get('items') or {}).get(item, 0))
            ok_quick = held >= qty
            note = 'held=%d qty=%d' % (held, qty)
    check('D16 README quick-start trade example is executable', ok_quick, note)

    # ── D17 archive-pending boundary documented ─────────────────────────────
    latest = changelog.split('\n## ', 1)[-1]
    recovery_docs = {
        PRIMARY: (primary, ('archive-pending', 'no automatic recovery',
                            'preserve the evidence', 'not an archive rollback')),
        SECONDARY: (secondary, ('archive-pending', '不会自动恢复', '保留现场',
                                '不等于磁盘归档回滚')),
        'CHANGELOG.md': (latest, ('archive-pending', '不会自动恢复', '保留现场',
                                  '不等于磁盘归档回滚')),
        'ARCHITECTURE.md': (arch, ('archive-pending', '不自动解析或恢复', '不承诺回滚磁盘归档')),
    }
    recovery_missing = [name for name, (text, terms) in recovery_docs.items()
                        if not all(term in text for term in terms)
                        or 'docs/ARCHIVE_RECOVERY.md' not in text]
    check('D17 archive-pending boundary and recovery guide are documented',
          not recovery_missing and os.path.isfile(os.path.join(ROOT, 'docs', 'ARCHIVE_RECOVERY.md')),
          str(recovery_missing))

    # ── D18 site does not hardcode gate results ─────────────────────────────
    site_text = re.sub(r'<[^>]+>', '', pages)
    numeric_claims = re.findall(r'\b\d+(?:\s*/\s*\d+)?\s*(?:变异测试|推前门禁|mutants|gate steps)',
                                site_text)
    check('D18 site does not hardcode mutation or gate results', not numeric_claims,
          str(numeric_claims))

    # ── D19 published counts match the metric ledger ────────────────────────
    ledger_checks = []
    if not metrics:
        ledger_checks.append('docs/metrics.json missing')
    else:
        expected = {
            'tools': tool_count,
            'rule_functions': rule_funcs,
            'verify_scripts': len(verify_scripts),
        }
        for key, actual in expected.items():
            if metrics.get(key) != actual:
                ledger_checks.append('%s ledger=%s actual=%s'
                                     % (key, metrics.get(key), actual))
        if metrics.get('version') != ver:
            ledger_checks.append('version ledger=%s actual=%s' % (metrics.get('version'), ver))
    check('D19 published counts match docs/metrics.json', not ledger_checks,
          str(ledger_checks[:3]))

    # ── D20 bilingual READMEs ───────────────────────────────────────────────
    links_ok = (SECONDARY in primary) and (PRIMARY in secondary)
    # The English README may quote Chinese only in sample payloads (bundle paths,
    # market keys). Prose must stay English: reject lines that are mostly CJK
    # outside fenced code blocks and inline code.
    prose = re.sub(r'```.*?```', '', primary, flags=re.S)
    prose = re.sub(r'`[^`]*`', '', prose)
    prose = re.sub(r'<[^>]+>', '', prose)
    cjk_lines = [ln.strip()[:40] for ln in prose.splitlines()
                 if len(re.findall(r'[\u4e00-\u9fff]', ln)) >= 6]
    check('D20 bilingual READMEs exist, cross-link, and English stays English',
          links_ok and not cjk_lines,
          'links=%s cjk_lines=%s' % (links_ok, cjk_lines[:2]))

    passed = sum(RESULTS)
    print('\n%d/%d passed' % (passed, len(RESULTS)))
    return 0 if passed == len(RESULTS) else 1


if __name__ == '__main__':
    sys.exit(main())
